function slugifyConstituency(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

// Complete 276 parliamentary constituencies of Ghana per the Electoral Commission of Ghana
export const EC_GHANA_CONSTITUENCIES: ConstituencyRecord[] = CONSTITUENCIES_BY_REGION.flatMap(
  (group) =>
    group.names.map((name, index) => ({
      id: `con-${slugifyConstituency(name)}`,
      regionId: group.regionId,
      name,
      code: `${group.prefix}-${String(index + 1).padStart(2, '0')}`,
    })),
);

